#pragma once
#include <stdint.h>
#include <time.h>
#include <string>
#include <sys/select.h>
#include "torrent.h"
#include "storage.h"
#include "download.h"
#include "writer.h"

// Состояние загрузки, которое передаётся наружу (для экрана).
struct SwarmStatus {
    uint64_t totalBytes;   // сколько байт получено за эту сессию
    int peers;             // сколько соединений открыто
    int ready;             // сколько прошли handshake и готовы к работе
    int sending;          // сколько из них присылали блоки за последние 10 секунд (реально работают)
    uint32_t haveCount;    // сколько кусков уже есть
    int speedKB;           // текущая скорость, КБ/с
};

// Загрузка одной раздачи со многими пирами. Не блокирует: общий цикл программы вызывает
// prepare(), затем один общий select() для всех раздач, затем process().
// Так можно качать несколько раздач одновременно в одном потоке.
// Недокачанный кусок, который при остановке записывается потоком записи.
struct PartialJobInfo {
    uint32_t index = 0;
    uint32_t nblocks = 0;
    std::vector<unsigned char> before;   // блоки, которые уже лежали на диске
    std::vector<unsigned char> after;    // они же плюс те, которые пишет задача (если она завершится успешно)
    WriteJobPtr job;                     // пусто, если писать было нечего
};

class Swarm {
public:
    Swarm(const Torrent& t, Storage& st, DownloadState& ds, const unsigned char peerId[20]);
    ~Swarm();

    // Служебная работа (освобождение застрявших кусков, запрос пиров, новые соединения) и
    // добавление своих сокетов в множества select. Возвращает наибольший номер сокета или -1.
    int prepare(time_t now, fd_set& rf, fd_set& wf);

    // Обработка того, что произошло: чтение и запись, запросы блоков, таймауты, скорость.
    void process(time_t now, fd_set& rf, fd_set& wf);

    bool finished() const;            // загрузка закончена (скачано или остановлена из-за ошибки)
    bool complete() const;            // скачано полностью
    const char* reason() const;       // почему закончена
    SwarmStatus status() const;
    void trim_memory();               // нехватка памяти: закрыть все соединения, освободить буферы
    void set_max_conns(int n);        // сколько соединений можно держать этой раздаче

    // Принять входящее соединение пира (уже прислал handshake, его байты в initial).
    // Возвращает: 1 принято и работает; 2 принято, но сразу закрыто (плохой пир, дубликат, нет места);
    // 0 не принято (сокет остаётся у вызывающего, он его закроет).
    int adopt(int fd, const std::string& key, const std::string& initial);

    // Дописывает ещё не сохранённые блоки недокачанных кусков в итоговые файлы и возвращает в parts
    // список таких кусков (его сохраняет вызывающий в файл прогресса). Результат: сколько блоков записано.
    // После перезапуска Swarm восстанавливает эти куски из ds.partials (читает блоки с диска).
    // Только при остановке раздачи! Передаёт потоку записи полученные, но ещё не записанные блоки недокачанных
    // кусков (подряд идущие блоки одной серией: на флешке важно число вызовов записи, а не их размер) вместе с
    // буферами кусков: после этого раздача данные больше не использует. Мелкие записи прямо в главном потоке
    // убивали отзывчивость программы. out: что и как записывается (из этого потом составляется файл .part).
    void persist_partials_async(std::vector<PartialJobInfo>& out);

    // Доделывает запись готовых (проверенных) кусков, которые ещё ждут своей очереди. budgetMs: сколько времени
    // можно потратить (остальное будет потеряно и скачается заново). Вызывается перед остановкой раздачи.
    void flush_writes(int budgetMs);

    // Считать все блоки недокачанных кусков ещё не записанными на диск (после сна консоли записи в кэше флешки
    // могли пропасть вместе с отключившейся флешкой): при завершении куска они будут записаны заново.
    void forget_persisted();

    int pending_writes() const;         // сколько проверенных кусков ждут записи на диск
    int failed_writes() const;          // сколько проверенных кусков записать не удалось

    // Остановка без ожидания записи: закрывает соединения с пирами и больше ничего не запрашивает. Кусок, который
    // ещё пишется на диск, дописывается потоком записи, а poll_writes() (его вызывает главный цикл) завершает его.
    void stop_network();
    // Завершает куски, которые поток записи уже записал. Возвращает, сколько ещё пишется.
    int poll_writes();

    // Сеть пропала и вернулась (сон консоли, смена адреса): пиры, которых мы "забанили" из-за оборвавшихся
    // соединений, снова доступны, а новый запрос к трекерам делается сразу.
    void network_changed();

private:
    struct Impl;
    Impl* p;
    Swarm(const Swarm&);              // копировать нельзя
    Swarm& operator=(const Swarm&);
};
