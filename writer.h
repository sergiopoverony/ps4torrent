#pragma once
// Поток записи на диск. Запись на флешку может занимать секунды даже для небольшого куска (на медленных
// накопителях около секунды на каждый вызов), а главный цикл программы один: пока он ждёт диск, стоят и
// сеть, и кнопки веб-страницы. Поэтому проверенные куски передаются этому потоку, а главный цикл идёт дальше.

#include <functional>
#include <memory>
#include <vector>
#include <atomic>
#include <stdint.h>
#include "bigbuf.h"
#include "storage.h"

struct WriteJob {
    Storage* st;                                            // куда писать (должен жить, пока задача не выполнена)
    uint32_t index;                                         // номер куска
    BigBuf buf;                                             // данные куска (задача владеет ими)
    std::vector<std::pair<uint32_t, uint32_t> > runs;       // что писать: (смещение в куске, длина)
    std::atomic<int> state;                                 // 0 в очереди, 1 пишется, 2 готово, 3 ошибка
    WriteJob() : st(NULL), index(0), state(0) {}
};
typedef std::shared_ptr<WriteJob> WriteJobPtr;

void writer_start();                    // запускает поток (один на программу)
void writer_stop(int waitMs);           // ждёт, пока очередь опустеет (не дольше waitMs), и останавливает поток
void writer_submit(const WriteJobPtr& job);
// Любая задача, связанная с диском (например, запись файла прогресса): выполняется потоком записи строго по порядку
// с остальными, так что видит результат ранее поставленных записей кусков. Функция не должна обращаться к данным
// главного потока: всё нужное копируется в неё при постановке.
void writer_post(std::function<void()> fn);
int writer_queue_length();              // сколько задач ждёт в очереди или выполняется
